export function isBadBlogImage(src) {
  const s = String(src || '').toLowerCase().trim()
  if (!s) return true
  if (s.includes('dubai_villa') || s.includes('monaco.jpg') || s.includes('atrium.jpg')) return true
  if (s.includes('tokyo.jpg') || s.includes('miami.jpg') || s.includes('spa_belgrade.jpg')) return true
  if (s.includes('hero.jpg') || s.includes('services-card.jpg')) return true
  return false
}

export function sanitizeBlogItem(item, idx = 0) {
  const fallback = DEFAULT_BLOGS[idx % DEFAULT_BLOGS.length]
  const image = isBadBlogImage(item.image) ? fallback.image : item.image
  const id = item.id || item._id || item.slug || `blog-${idx + 1}`
  const slug = item.slug || item.id || id

  return {
    ...fallback,
    ...item,
    id,
    slug,
    image,
    title: item.title || fallback.title,
    excerpt: item.excerpt || fallback.excerpt,
    category: item.category || fallback.category,
    author: item.author || fallback.author,
    date: item.date || fallback.date,
    readTime: item.readTime || fallback.readTime,
    tag: item.tag || fallback.tag,
    published: item.published !== false,
    featured: Boolean(item.featured),
    content: Array.isArray(item.content) && item.content.length > 0 ? item.content : fallback.content,
  }
}

export function getStoredBlogs() {
  try {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('ug_studio_blogs')
      if (saved) {
        const parsed = JSON.parse(saved)
        if (Array.isArray(parsed) && parsed.length > 0) {
          const hasBadImages = parsed.some((p) => isBadBlogImage(p?.image))
          if (!hasBadImages && parsed.length >= DEFAULT_BLOGS.length) {
            return parsed.map((p, idx) => sanitizeBlogItem(p, idx))
          }
        }
      }
    }
  } catch {}
  return DEFAULT_BLOGS.map((p, idx) => sanitizeBlogItem(p, idx))
}

export function setStoredBlogs(list) {
  const cleanList = (Array.isArray(list) ? list : []).map((p, idx) => sanitizeBlogItem(p, idx))
  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('ug_studio_blogs', JSON.stringify(cleanList))
      window.dispatchEvent(new Event('ug_blogs_updated'))
    }
  } catch {}
  return cleanList
}
